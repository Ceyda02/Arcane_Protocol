export function localizeBestiaryCreature(creature, language) {
  if (language !== 'tr') return creature;
  const translation = creature.grimoire !== undefined
    ? REALM_TRANSLATIONS[creature.id]
    : { ...MALWARE_TRANSLATIONS[creature.id], ...MALWARE_STUDY_TRANSLATIONS[creature.id] };
  return translation ? { ...creature, ...translation } : creature;
}

export function localizeBestiaryPage(page, language) {
  if (!page || language !== 'tr' || !page.id.startsWith('beast-')) return page;
  const creature = MALWARE_CREATURES.find((item) => `beast-${item.id}` === page.id);
  if (!creature) return page;
  const localized = localizeBestiaryCreature(creature, language);
  return {
    ...page,
    title: `${localized.name}: ${localized.malwareType}`,
    category: 'Threats & Malware',
    source: localized.title,
    concept: localized.malwareType,
    plain: localized.definition,
    technical: `${localized.behavior} ${localized.distinguish}`,
    example: { label: 'Kurgusal kanıt', text: localized.evidence.join('\n') },
    mistake: localized.distinguish,
    takeaway: localized.defense,
  };
}
